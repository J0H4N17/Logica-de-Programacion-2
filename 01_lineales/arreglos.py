
# TEMA: ARREGLOS (ARRAY)

# Ejemplo 1: Notas de estudiantes
notas = [4.0, 3.5, 4.5, 3.8, 5.0]
print("Notas:", notas)

# Ejemplo 2: Precios de productos
precios = [1000, 2500, 3000, 4500, 5000]
print("Precios:", precios)

# Ejemplo 3: Temperaturas de la semana
temperaturas = [22, 24, 23, 25, 21]
print("Temperaturas:", temperaturas)

# Ejemplo 4: Integrantes de un equipo
equipo = ["Ana", "Luis", "Pedro", "Sofia", "Carlos"]
print("Equipo:", equipo)

# Ejemplo 5: Edades de personas
edades = [18, 20, 21, 19, 22]
print("Edades:", edades)

# Acceder a una posición
print("Primera nota:", notas[0])
